let current = 'bn';
try { current = localStorage.getItem('panda.lang') || 'bn'; } catch (_) {}
if (!DICT[current]) current = 'bn';

const listeners = new Set();

export function t(key, vars = {}) {
  let s = (DICT[current] && DICT[current][key]) ?? DICT.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
export const lang = () => current;
export function setLang(next) {
  if (!DICT[next]) return;
  current = next;
  try { localStorage.setItem('panda.lang', next); } catch (_) {}
  document.documentElement.lang = next;
  for (const fn of listeners) { try { fn(next); } catch (e) { console.error(e); } }
}
export const onLangChange = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };
export const isBn = () => current === 'bn';

/** Relative time in the active language. */
export function agoLabel(ts) {
  const s = Math.max(0, Math.floor((Date.now() - ts) / 1000));
  if (s < 60) return t('now');
  const m = Math.floor(s / 60);
  if (m < 60) return isBn() ? `${m} মি` : `${m}m`;
  const h = Math.floor(m / 60);
  if (h < 24) return isBn() ? `${h} ঘ` : `${h}h`;
  const d = Math.floor(h / 24);
  if (d < 7) return isBn() ? `${d} দি` : `${d}d`;
  return new Date(ts).toLocaleDateString(isBn() ? 'bn-BD' : 'en-GB', { month: 'short', day: 'numeric' });
}
